# Description:
# This script extracts and summarizes between-cohort
# heterogeneity statistics (Cochran’s Q and I²) from METAL
# meta-analysis output for genome-wide significant CpG sites.
#
# This analysis evaluates whether meta-analytic associations
# are consistent between RODAM (Ghanaians) and AADM (Nigerians).
#
# Notes:
# - Heterogeneity statistics are generated by METAL
# - No re-estimation of effects is performed
